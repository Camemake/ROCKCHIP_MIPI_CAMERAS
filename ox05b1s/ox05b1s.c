/*
 * OmniVision OX05B1S on the Luckfox Aura CSI1 connector.
 *
 * Same module as the Pi 5 path. The register table is the 2592x1944 list
 * from that driver. It writes 0x3010 = 0x41, which is 4 lanes. The table
 * was captured at 12 MHz. This module's crystal is 27 MHz, so link_mhz
 * defaults to 450, the rate the Pi receiver locked at 900 Mbps.
 * Leave CSI1 IO0 as a GPIO input. Driving it stops the crystal.
 */

